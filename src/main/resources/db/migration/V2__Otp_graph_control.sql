-- Emergency controls of the OTP graph publication (see Otp2GraphControlService).
-- The state of the publication (current graph and pin of each serialization version) lives in the graph bucket, next
-- to the graph files. The database only serializes the writers and keeps the audit trail.
-- Plain SQL shared by PostgreSQL and the H2 database used in tests: timestamps are bound from Java.

-- Single row locked (SELECT ... FOR UPDATE) to apply the graph promotions and the control operations one at a time
-- across the cluster.
CREATE TABLE IF NOT EXISTS otp_graph_control (
    id integer NOT NULL,
    CONSTRAINT otp_graph_control_pk PRIMARY KEY (id),
    CONSTRAINT otp_graph_control_singleton CHECK (id = 1)
);
INSERT INTO otp_graph_control (id) VALUES (1);

-- Audit of the control operations and of the builds that were not promoted.
CREATE TABLE IF NOT EXISTS otp_graph_control_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    action character varying(50) NOT NULL,
    serialization_id character varying(100),
    graph_file character varying(500),
    performed_by character varying(255) NOT NULL,
    performed_at timestamp with time zone NOT NULL,
    reason character varying(1000),
    CONSTRAINT otp_graph_control_audit_pk PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS otp_graph_control_audit_performed_at_idx ON otp_graph_control_audit (performed_at);
