-- Emergency controls of the OTP graph publication (see Otp2GraphControlService).
-- Plain SQL shared by PostgreSQL and the H2 database used in tests: timestamps are bound from Java.

-- Single row holding the pause state of the graph builder.
-- The row is also locked (SELECT ... FOR UPDATE) to serialize the graph promotions and the control operations.
CREATE TABLE IF NOT EXISTS otp_graph_control (
    id integer NOT NULL,
    paused boolean NOT NULL,
    paused_by character varying(255),
    paused_at timestamp with time zone,
    pause_reason character varying(1000),
    CONSTRAINT otp_graph_control_pk PRIMARY KEY (id),
    CONSTRAINT otp_graph_control_singleton CHECK (id = 1)
);
INSERT INTO otp_graph_control (id, paused) VALUES (1, false);

-- Graph pinned as the current graph of a serialization version: new builds are not promoted.
CREATE TABLE IF NOT EXISTS otp_graph_pin (
    serialization_id character varying(100) NOT NULL,
    graph_file character varying(500) NOT NULL,
    pinned_by character varying(255) NOT NULL,
    pinned_at timestamp with time zone NOT NULL,
    reason character varying(1000) NOT NULL,
    CONSTRAINT otp_graph_pin_pk PRIMARY KEY (serialization_id)
);

-- Graph build requests received while the graph builder is paused, replayed when it is resumed.
-- The attributes are the headers of the PubSub message, as a JSON object.
CREATE TABLE IF NOT EXISTS otp_graph_deferred_build_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    graph_type character varying(20) NOT NULL,
    pubsub_message_id character varying(255),
    attributes character varying(65535) NOT NULL,
    received_at timestamp with time zone NOT NULL,
    CONSTRAINT otp_graph_deferred_build_request_pk PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS otp_graph_deferred_build_request_message_uindex ON otp_graph_deferred_build_request (pubsub_message_id);

-- Log of the control operations and of the graphs that were not promoted.
CREATE TABLE IF NOT EXISTS otp_graph_control_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    action character varying(50) NOT NULL,
    serialization_id character varying(100),
    graph_file character varying(500),
    performed_by character varying(255) NOT NULL,
    performed_at timestamp with time zone NOT NULL,
    reason character varying(1000),
    CONSTRAINT otp_graph_control_audit_pk PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS otp_graph_control_audit_performed_at_index ON otp_graph_control_audit (performed_at);
